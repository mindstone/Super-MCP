import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJsonPath = path.join(repositoryRoot, "package.json");
const generatedPath = path.join(repositoryRoot, "src", "buildVersion.generated.ts");

const packageMetadata = JSON.parse(await readFile(packageJsonPath, "utf8"));
const version = packageMetadata?.version;
if (typeof version !== "string" || version.length === 0) {
  throw new Error("super-mcp package version is missing at build time");
}

const generatedSource = `// Generated by scripts/generate-build-version.mjs. Do not edit by hand.
// The value is compiled into dist so packaged runtimes never read package.json.
export const GENERATED_SUPER_MCP_BUILD_VERSION = ${JSON.stringify(version)} as const;
`;

await writeFile(generatedPath, generatedSource, "utf8");
